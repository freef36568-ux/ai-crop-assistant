const allFiles = fs.readdirSync(i18nDir).filter(f => f.endsWith('.json'));

allFiles.forEach(file => {
  const lang = file.replace('.json', '');
  const filePath = path.join(i18nDir, file);
  let data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  const updates = updatesByLang[lang] || updatesByLang['en'];

  for (const section in updates) {
    if (!data[section]) data[section] = {};
    for (const key in updates[section]) {
      data[section][key] = updates[section][key];
    }
  }

  // Ensure any fallback keys from English exist in all languages
  for (const section in updatesByLang.en) {
    if (!data[section]) data[section] = {};
    for (const key in updatesByLang.en[section]) {
      if (!data[section][key]) {
        data[section][key] = updatesByLang.en[section][key];
      }
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
  console.log(`Updated translations for ${file}`);
});
